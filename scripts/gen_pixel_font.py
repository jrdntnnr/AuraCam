#!/usr/bin/env python3
"""Generate the Cardputer's LVGL font from the HUD's 5x7 pixel glyphs.

The Cardputer screen uses the same font as the HUD burned into frames, so
the glyph table in auracam/hud.py stays the single source.

    uv run --project . python scripts/gen_pixel_font.py > cardputer/fonts/aura_pixel_7.c
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from auracam.hud import glyph_rows  # noqa: E402

FONT_NAME = "aura_pixel_7"
FIRST_CHAR = 0x20
LAST_CHAR = 0x7E
GLYPH_WIDTH = 5
GLYPH_HEIGHT = 7
ADVANCE_PX = 6
LINE_HEIGHT = 10
BASE_LINE = 2
# LVGL stores advance widths in 1/16 px.
ADVANCE_UNITS = ADVANCE_PX * 16


def pack(rows: tuple[int, ...]) -> list[int]:
    """Pack a glyph as a continuous MSB-first 1-bpp stream (LVGL plain format)."""
    bits = []
    for row in rows:
        bits.extend((row >> (GLYPH_WIDTH - 1 - x)) & 1 for x in range(GLYPH_WIDTH))
    while len(bits) % 8:
        bits.append(0)
    return [
        sum(bit << (7 - index) for index, bit in enumerate(bits[start : start + 8]))
        for start in range(0, len(bits), 8)
    ]


def main() -> None:
    bitmap: list[int] = []
    descriptors = ["    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0}"]
    for code in range(FIRST_CHAR, LAST_CHAR + 1):
        char = chr(code)
        if char == " ":
            descriptors.append(
                f"    {{.bitmap_index = 0, .adv_w = {ADVANCE_UNITS}, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0}} /* ' ' */"
            )
            continue
        index = len(bitmap)
        bitmap.extend(pack(glyph_rows(char)))
        label = "\\\\" if char == "\\" else char
        descriptors.append(
            f"    {{.bitmap_index = {index}, .adv_w = {ADVANCE_UNITS}, .box_w = {GLYPH_WIDTH}, "
            f".box_h = {GLYPH_HEIGHT}, .ofs_x = 0, .ofs_y = 0}} /* '{label}' */"
        )

    lines = ", ".join(f"0x{byte:02x}" for byte in bitmap)
    count = LAST_CHAR - FIRST_CHAR + 1
    print(f"""/* Generated by scripts/gen_pixel_font.py from auracam/hud.py. Do not edit. */
#include "lvgl.h"

static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {{
    {lines}
}};

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{",\n".join(descriptors)}
}};

static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{.range_start = {FIRST_CHAR}, .range_length = {count}, .glyph_id_start = 1,
     .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0,
     .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}}
}};

static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .kern_dsc = NULL,
    .kern_scale = 0,
    .cmap_num = 1,
    .bpp = 1,
    .kern_classes = 0,
    .bitmap_format = 0,
}};

const lv_font_t {FONT_NAME} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {LINE_HEIGHT},
    .base_line = {BASE_LINE},
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = -1,
    .underline_thickness = 1,
    .dsc = &font_dsc,
    .fallback = NULL,
    .user_data = NULL,
}};""")


if __name__ == "__main__":
    main()
